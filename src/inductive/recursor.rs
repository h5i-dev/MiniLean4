//! Generation of recursor types (Section "The recursor" in the text):
//!
//! ```text
//! I.rec_v : Pi (ps : Ps).
//!           Pi (M : Pi (is : Js). I ps is -> Sort v).  -- motive
//!           Pi (m_1 : C_1) ... Pi (m_n : C_n).          -- minor premises
//!           Pi (is : Js). Pi (x : I ps is). M is x      -- indices, major premise
//!
//! C_j     = Pi (as : As_j). Pi (hs : Hs_j). M ts_j (c_j ps as)
//! H_{j,k} = Pi (ys : Bs). M ss (a_k ys)
//!           for each recursive field a_k : Pi (ys : Bs). I ps ss
//! ```

use crate::{
    declaration::{
        ConstructorInfo, Context, Decl, DeclKind, InductiveInfo, RecursiveFieldInfo, RecursorInfo,
    },
    kernel::{Kernel, Result},
    term::{apps, arrow, const_term, pi, telescope, var, Term},
};

use super::apply_inductive;

/// Binder names generated by the kernel. They start with `__`, which user
/// declarations may not use, so they never clash with parameters or fields.
pub(crate) const MOTIVE: &str = "__motive";
pub(crate) const MAJOR_PREMISE: &str = "__major";
pub(crate) const MINOR_PREMISE_PREFIX: &str = "__minor_";
pub(crate) const INDUCTION_HYPOTHESIS_PREFIX: &str = "__ih_";

/// `I.rec`, the prefix of every recursor name of `I`.
pub(crate) fn recursor_namespace(inductive: &str) -> String {
    format!("{inductive}.rec")
}

/// `I.rec_v`
pub(crate) fn recursor_name(inductive: &str, elimination_universe: u64) -> String {
    format!("{inductive}.rec{elimination_universe}")
}

/// `M is x`
fn apply_motive(indices: &[Term], value: Term) -> Term {
    apps(
        var(MOTIVE),
        indices.iter().cloned().chain(std::iter::once(value)),
    )
}

impl Kernel {
    /// Adds `I.rec_v` for `v = elimination_universe`, if it is not already
    /// present. Levels 0 and 1 are added by `add_inductive`; call this before
    /// using `I.rec_v` for `v > 1`.
    ///
    /// Fails if `I` is a proposition that does not allow large elimination
    /// and `v > 0`.
    pub fn register_recursor(&mut self, inductive: &str, elimination_universe: u64) -> Result<()> {
        let info = self
            .inductives
            .get(inductive)
            .ok_or_else(|| format!("unknown inductive family: {inductive}"))?;
        if info.universe_level == 0 && elimination_universe > 0 && !info.large_elimination {
            return Err(format!(
                "{inductive} is not a subsingleton proposition; cannot eliminate into Sort {elimination_universe}"
            ));
        }
        let name = recursor_name(inductive, elimination_universe);
        if self.decls.contains_key(&name) {
            return Ok(());
        }
        let recursor_type = recursor_type(info, elimination_universe);
        let major_argument_index =
            info.params.len() + 1 + info.constructors.len() + info.indices.len();
        self.decls.insert(
            name,
            Decl {
                ty: recursor_type,
                kind: DeclKind::Recursor(RecursorInfo {
                    inductive: inductive.to_string(),
                    elimination_universe,
                    major_argument_index,
                }),
            },
        );
        Ok(())
    }
}

/// `Pi (ps : Ps). Pi (M : ...). Pi (ms : Cs). Pi (is : Js). Pi (x : I ps is). M is x`
fn recursor_type(info: &InductiveInfo, elimination_universe: u64) -> Term {
    let index_args: Vec<Term> = info.indices.iter().map(|(i, _)| var(i)).collect();
    let minor_premises: Context = info
        .constructors
        .iter()
        .enumerate()
        .map(|(j, constructor)| {
            (
                format!("{MINOR_PREMISE_PREFIX}{j}"),
                minor_premise_type(info, j, constructor),
            )
        })
        .collect();
    let major_premise_type = apply_inductive(&info.name, &info.params, index_args.clone());
    let indices_and_major = telescope(
        &info.indices,
        pi(
            MAJOR_PREMISE,
            major_premise_type,
            apply_motive(&index_args, var(MAJOR_PREMISE)),
        ),
    );
    telescope(
        &info.params,
        pi(
            MOTIVE,
            motive_type(info, elimination_universe),
            telescope(&minor_premises, indices_and_major),
        ),
    )
}

/// `Pi (is : Js). I ps is -> Sort v`
fn motive_type(info: &InductiveInfo, elimination_universe: u64) -> Term {
    let index_args = info.indices.iter().map(|(i, _)| var(i));
    telescope(
        &info.indices,
        arrow(
            apply_inductive(&info.name, &info.params, index_args),
            Term::Sort(elimination_universe),
        ),
    )
}

/// `C_j = Pi (as : As_j). Pi (hs : Hs_j). M ts_j (c_j ps as)`
fn minor_premise_type(info: &InductiveInfo, j: usize, constructor: &ConstructorInfo) -> Term {
    // c_j ps as
    let constructor_application = apps(
        const_term(&constructor.name),
        info.params
            .iter()
            .chain(constructor.fields.iter())
            .map(|(name, _)| var(name)),
    );
    // (as : As_j) followed by (hs : Hs_j)
    let mut minor_premise_binders = constructor.fields.clone();
    for (k, recursive_field) in constructor.recursive_fields.iter().enumerate() {
        minor_premise_binders.push((
            format!("{INDUCTION_HYPOTHESIS_PREFIX}{j}_{k}"),
            induction_hypothesis_type(constructor, recursive_field),
        ));
    }
    telescope(
        &minor_premise_binders,
        apply_motive(&constructor.result_indices, constructor_application),
    )
}

/// `H_{j,k} = Pi (ys : Bs). M ss (a_k ys)`
fn induction_hypothesis_type(
    constructor: &ConstructorInfo,
    recursive_field: &RecursiveFieldInfo,
) -> Term {
    let field_name = &constructor.fields[recursive_field.constructor_field_index].0;
    let applied_field = apps(
        var(field_name),
        recursive_field.argument_binders.iter().map(|(y, _)| var(y)),
    );
    telescope(
        &recursive_field.argument_binders,
        apply_motive(&recursive_field.target_indices, applied_field),
    )
}
