//! Inductive declarations (Section "Inductive Declarations" in the text).
//!
//! Reading order:
//! 1. [`Kernel::add_inductive`] (this file): the acceptance conditions 1-4,
//!    then registration of the type former and constructors.
//! 2. `positivity.rs`: condition 3, strict positivity of recursive fields.
//! 3. `recursor.rs`: generation of the recursor type `I.rec_v`.
//!
//! The iota-rules are not generated as terms. [`crate::reduction`] applies them
//! directly from the stored [`InductiveInfo`].

