use std::collections::HashSet;

use crate::{
    declaration::{
        ConstructorInfo, ConstructorSpec, Context, Decl, DeclKind, InductiveInfo, InductiveSpec,
    },
    kernel::{Kernel, Result},
    substitution::fv,
    term::{apps, const_term, occurs_const, telescope, var, Term},
};

use positivity::check_recursive_fields;
use recursor::{recursor_name, recursor_namespace};

/// `I ps ts`: the inductive type `I` applied to its parameters (as variables)
/// and to the given index terms.
pub(crate) fn apply_inductive(
    inductive: &str,
    params: &Context,
    indices: impl IntoIterator<Item = Term>,
) -> Term {
    apps(
        const_term(inductive),
        params.iter().map(|(p, _)| var(p)).chain(indices),
    )
}

/// Is `name` reserved for names generated by the kernel (`__motive`, `_`, ...)?
fn is_reserved_binder(name: &str) -> bool {
    name.starts_with("__") || name == "_"
}

impl Kernel {
    /// Checks an inductive declaration and, if it is accepted, adds to the
    /// signature the type former `I`, its constructors, and the recursors
    /// `I.rec0` and (if large elimination is allowed) `I.rec1`.
    ///
    /// This is the only way to add constructor and recursor metadata.
    /// On failure the signature is left unchanged.
    pub fn add_inductive(&mut self, spec: InductiveSpec) -> Result<()> {
        self.check_names_and_arities(&spec)?;
        // Condition 1: the type of I is a type.
        self.check_inductive_type(&spec)?;

        // Conditions 2-4 are checked with I in the signature, so that
        // constructor fields can mention I.
        self.register_type_former(&spec);
        let constructors = match self.check_constructors(&spec) {
            Ok(constructors) => constructors,
            Err(e) => {
                self.decls.remove(&spec.name);
                return Err(e);
            }
        };
        self.register_constructors(&spec, &constructors);

        let large_elimination = self.allows_large_elimination(&spec, &constructors)?;
        self.inductives.insert(
            spec.name.clone(),
            InductiveInfo {
                name: spec.name.clone(),
                params: spec.params,
                indices: spec.indices,
                universe_level: spec.universe_level,
                constructors,
                large_elimination,
            },
        );
        self.register_recursor(&spec.name, 0)?;
        if large_elimination {
            self.register_recursor(&spec.name, 1)?;
        }
        Ok(())
    }

    /// Syntactic checks done before any type checking: the new names are free
    /// and well-formed, binders are distinct and not reserved, and every
    /// constructor has one index term per index.
    fn check_names_and_arities(&self, spec: &InductiveSpec) -> Result<()> {
        self.ensure_new(&spec.name)?;
        if spec.name.contains(".rec") {
            return Err("reserved recursor namespace".into());
        }
        let header_binders = spec.params.iter().chain(spec.indices.iter());
        if header_binders.clone().any(|(name, _)| is_reserved_binder(name)) {
            return Err("reserved binder name".into());
        }
        // Recursor levels above 1 are generated on demand by register_recursor.
        for level in 0..=1 {
            self.ensure_new(&recursor_name(&spec.name, level))?;
        }
        // Parameter, index, and constructor names share one namespace here.
        let mut seen = HashSet::new();
        for (name, _) in header_binders {
            if !seen.insert(name.clone()) {
                return Err(format!("duplicate binder {name}"));
            }
        }
        for constructor in &spec.constructors {
            self.ensure_new(&constructor.name)?;
            let qualified_prefix = format!("{}.", spec.name);
            if constructor.name == spec.name || !constructor.name.starts_with(&qualified_prefix) {
                return Err("constructor must be qualified by its inductive name".into());
            }
            if constructor
                .fields
                .iter()
                .any(|(name, _)| is_reserved_binder(name))
            {
                return Err("reserved field name".into());
            }
            if !seen.insert(constructor.name.clone()) {
                return Err("duplicate constructor".into());
            }
            if constructor.name.starts_with(&recursor_namespace(&spec.name)) {
                return Err("constructor conflicts with generated recursor".into());
            }
            if constructor.result_indices.len() != spec.indices.len() {
                return Err("incorrect constructor index arity".into());
            }
        }
        Ok(())
    }

    /// Condition 1: `Pi (ps : Ps). Pi (is : Js). Sort u` is a type, i.e. each
    /// parameter and index type is a type in the context of the earlier ones.
    fn check_inductive_type(&self, spec: &InductiveSpec) -> Result<()> {
        let mut parameter_and_index_context = vec![];
        for (name, ty) in spec.params.iter().chain(spec.indices.iter()) {
            self.infer_sort(&parameter_and_index_context, ty)?;
            parameter_and_index_context.push((name.clone(), ty.clone()));
        }
        Ok(())
    }

    /// Adds `I : Pi (ps : Ps). Pi (is : Js). Sort u` to the signature.
    fn register_type_former(&mut self, spec: &InductiveSpec) {
        let inductive_type = telescope(
            &spec.params,
            telescope(&spec.indices, Term::Sort(spec.universe_level)),
        );
        self.decls.insert(
            spec.name.clone(),
            Decl {
                ty: inductive_type,
                kind: DeclKind::Inductive,
            },
        );
    }

    /// Conditions 2-4 for every constructor. Requires `I` in the signature.
    fn check_constructors(&self, spec: &InductiveSpec) -> Result<Vec<ConstructorInfo>> {
        let mut checked_constructors = vec![];
        for constructor in &spec.constructors {
            let constructor_context = self.check_constructor_fields(spec, constructor)?;
            let recursive_fields = check_recursive_fields(spec, constructor)?;
            self.check_constructor_result(spec, constructor, &constructor_context)?;
            checked_constructors.push(ConstructorInfo {
                name: constructor.name.clone(),
                fields: constructor.fields.clone(),
                result_indices: constructor.result_indices.clone(),
                recursive_fields,
            });
        }
        Ok(checked_constructors)
    }

    /// Each field type is a type in the context `ps, a_1, ..., a_{i-1}`, and
    /// (condition 4) lies in a universe no larger than `Sort u` when `u >= 1`.
    ///
    /// Returns the constructor context `(ps : Ps) (as : As_j)`.
    fn check_constructor_fields(
        &self,
        spec: &InductiveSpec,
        constructor: &ConstructorSpec,
    ) -> Result<Context> {
        let mut constructor_context = spec.params.clone();
        for (field_name, field_type) in &constructor.fields {
            if constructor_context.iter().any(|(prev, _)| prev == field_name) {
                return Err("duplicate field or parameter".into());
            }
            let field_universe = self.infer_sort(&constructor_context, field_type)?;
            if spec.universe_level >= 1 && field_universe > spec.universe_level {
                return Err(format!(
                    "field {field_name} lives in Sort {field_universe}, exceeding inductive universe Sort {}",
                    spec.universe_level
                ));
            }
            constructor_context.push((field_name.clone(), field_type.clone()));
        }
        Ok(constructor_context)
    }

    /// Condition 2: the result type `I ps ts_j` does not mention `I` inside the
    /// index terms `ts_j`, and lives in `Sort u`.
    fn check_constructor_result(
        &self,
        spec: &InductiveSpec,
        constructor: &ConstructorSpec,
        constructor_context: &Context,
    ) -> Result<()> {
        if constructor
            .result_indices
            .iter()
            .any(|index| occurs_const(index, &spec.name))
        {
            return Err("inductive occurrence inside result index".into());
        }
        let constructor_result_type = apply_inductive(
            &spec.name,
            &spec.params,
            constructor.result_indices.iter().cloned(),
        );
        if self.infer_sort(constructor_context, &constructor_result_type)? != spec.universe_level {
            return Err("constructor result has wrong universe".into());
        }
        Ok(())
    }

    /// Adds `c_j : Pi (ps : Ps). Pi (as : As_j). I ps ts_j` for every constructor.
    fn register_constructors(&mut self, spec: &InductiveSpec, constructors: &[ConstructorInfo]) {
        for constructor in constructors {
            let result_type = apply_inductive(
                &spec.name,
                &spec.params,
                constructor.result_indices.iter().cloned(),
            );
            let constructor_type =
                telescope(&spec.params, telescope(&constructor.fields, result_type));
            self.decls.insert(
                constructor.name.clone(),
                Decl {
                    ty: constructor_type,
                    kind: DeclKind::Constructor,
                },
            );
        }
    }

    /// May `I` be eliminated into `Sort v` for `v >= 1`?
    ///
    /// Always, if `u >= 1`. If `I` is a proposition (`u = 0`), only if it is a
    /// *subsingleton*: at most one constructor, and every field is a proof or
    /// occurs in the index terms `ts_j`.
    fn allows_large_elimination(
        &self,
        spec: &InductiveSpec,
        constructors: &[ConstructorInfo],
    ) -> Result<bool> {
        if spec.universe_level >= 1 {
            return Ok(true);
        }
        if constructors.len() > 1 {
            return Ok(false);
        }
        for constructor in constructors {
            let mut constructor_context = spec.params.clone();
            for (field_name, field_type) in &constructor.fields {
                let is_proof = self.infer_sort(&constructor_context, field_type)? == 0;
                let occurs_in_indices = constructor
                    .result_indices
                    .iter()
                    .any(|index| fv(index).contains(field_name));
                if !is_proof && !occurs_in_indices {
                    return Ok(false);
                }
                constructor_context.push((field_name.clone(), field_type.clone()));
            }
        }
        Ok(true)
    }
}
